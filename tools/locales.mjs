const LIMITS = { extName: 45, extDescription: 132 };

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const keys = Object.keys(L.en);
let problems = 0;

for (const [lang, table] of Object.entries(L)) {
    const messages = {};
    for (const key of keys) {
        const text = table[key];
        if (typeof text !== 'string') { console.error(`${lang}: missing ${key}`); problems++; continue; }
        if (LIMITS[key] && [...text].length > LIMITS[key]) { console.error(`${lang}: ${key} is ${[...text].length} chars (max ${LIMITS[key]})`); problems++; }
        const subs = [...new Set(text.match(/\{\d\}/g) || [])];
        if (subs.join() !== [...new Set(L.en[key].match(/\{\d\}/g) || [])].join()) { console.error(`${lang}: ${key} substitutions differ from en`); problems++; }
        const entry = { message: text.replace(/\$/g, '$$$$').replace(/\{(\d)\}/g, (m, n) => `$P${n}$`) };
        if (subs.length) entry.placeholders = Object.fromEntries(subs.map((m) => [`p${m[1]}`, { content: `$${Number(m[1]) + 1}` }]));
        messages[key] = entry;
    }
    for (const key of Object.keys(table)) if (!keys.includes(key)) { console.error(`${lang}: unknown key ${key}`); problems++; }
    const dir = path.join(root, '_locales', lang);
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(path.join(dir, 'messages.json'), JSON.stringify(messages, null, 2) + '\n');
}

console.log(problems ? `${problems} problem(s)` : `ok: ${Object.keys(L).length} languages, ${keys.length} strings`);
process.exit(problems ? 1 : 0);
